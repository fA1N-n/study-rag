// Маскирование ПДн перед отправкой в LLM. Критерии P1–P8. Примеры — по образцу титульников из датасета, имена выдуманы.
import { describe, expect, it } from "vitest";
import { maskPii } from "./pii";

describe("maskPii", () => {
  it("P1: почта → [почта]", () => {
    const r = maskPii("пишите на ivanov.ii@mail.ru до пятницы");
    expect(r.text).toBe("пишите на [почта] до пятницы");
    expect(r.found.emails).toBe(1);
  });

  it("P2: телефоны в разных записях → [телефон]", () => {
    const r = maskPii("+7 917 111-22-33, +7(905)342-00-07, 89001234567, +79161234567");
    expect(r.text).toBe("[телефон], [телефон], [телефон], [телефон]");
    expect(r.found.phones).toBe(4);
  });

  it("P2: номера групп, годы, двоичные числа и страницы не трогаем", () => {
    const s = "группа 4107, 2025 год, число 11101012 = 11710, стр. 12, ГОСТ 7.32-2017";
    expect(maskPii(s).text).toBe(s);
  });

  it("P3: «Фамилия И.О.», «Фамилия И. О.», «И.О. Фамилия» → [ФИО]", () => {
    expect(maskPii("Выполнил: Петрова К.С.").text).toBe("Выполнил: [ФИО]");
    expect(maskPii("Проверил Сидоров А. Б., доцент").text).toBe("Проверил [ФИО], доцент");
    expect(maskPii("автор — К.С. Петрова").text).toBe("автор — [ФИО]");
  });

  it("P4: имя после «Студента группы NNNN» на следующих строках → [ФИО]", () => {
    const r = maskPii("Студента группы 4107\n\nПетровой Ксении\n\nКазань 2024");
    expect(r.text).toBe("Студента группы 4107\n\n[ФИО]\n\nКазань 2024");
    expect(r.found.names).toBe(1);
  });

  it("P4: «Выполнила студентка гр. 4307 Иванова Мария Петровна» → [ФИО]", () => {
    expect(maskPii("Выполнила студентка гр. 4307 Иванова Мария Петровна").text).toBe("Выполнила студентка гр. 4307 [ФИО]");
  });

  it("P4: «Обучающийся группы №4107 Петров Иван Сергеевич» и «Обучающаяся 4107\\nПетрова Анна» → [ФИО]", () => {
    expect(maskPii("Обучающийся группы №4107 Петров Иван Сергеевич").text).toBe("Обучающийся группы №4107 [ФИО]");
    expect(maskPii("Обучающаяся 4107\nПетрова Анна").text).toBe("Обучающаяся 4107\n[ФИО]");
  });

  it("P5: фамилии из списка (преподаватели) не маскируются, в том числе в другом падеже", () => {
    const keep = ["Шакирова Алсу Ринатовна"];
    expect(maskPii("Проверил: преподаватель Шакирова А.А.", { keepNames: keep }).text).toBe("Проверил: преподаватель Шакирова А.А.");
    expect(maskPii("у Шакировой А.А. и Петрова К.С.", { keepNames: keep }).text).toBe("у Шакировой А.А. и [ФИО]");
  });

  it("P6: флаг ПДн — есть замены; без замен — false", () => {
    expect(maskPii("Выполнил: Петрова К.С.").piiFlag).toBe(true);
    expect(maskPii("Лекция 5. Семафоры").piiFlag).toBe(false);
    expect(maskPii("Шакирова А.А.", { keepNames: ["Шакирова А. Р."] }).piiFlag).toBe(false);
  });

  it("P7: повторное маскирование ничего не меняет", () => {
    const once = maskPii("Выполнил: Петрова К.С., тел. +7 917 111-22-33, a@b.ru").text;
    expect(maskPii(once).text).toBe(once);
  });

  it("P8: «им. А.Н. Туполева», «т.е.», «Рис. 1.» не маскируются", () => {
    const s = "КНИТУ-КАИ им. А.Н. Туполева; т.е. см. Рис. 1. и Т.е. так";
    expect(maskPii(s).text).toBe(s);
  });

  it("P8: пустой и большой вход", () => {
    expect(maskPii("").text).toBe("");
    const big = "Лекция про семафоры. ".repeat(20_000) + "Петрова К.С.";
    const t0 = performance.now();
    expect(maskPii(big).text.endsWith("[ФИО]")).toBe(true);
    expect(performance.now() - t0).toBeLessThan(2000);
  });
});
